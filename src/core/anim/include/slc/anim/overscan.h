#pragma once

#include <cinder/Rect.h>

namespace slc::anim {

/// Uniform draw-scale that guarantees a cell's texture quad still covers
/// the whole `clip` rect under worst-case cell motion.
///
/// The quad is `drawn` scaled by the return value about a pivot that can
/// sit up to `driftPx` off the clip centre on either axis, then rotated by
/// up to `maxRotDeg`. Rotating the clip rect's corners into the quad frame
/// shows the margin each axis needs: a corner's extent is
/// half·cos(rot) + otherHalf·sin(rot), so the short axis of an elongated
/// cell must absorb rotation lift generated by the LONG axis — a flat
/// "drift/longest-side" margin under-covers wide cells and lets the dark
/// underlay sweep in at the seam as the quad rocks.
[[nodiscard]] float cellOverscanScale(const ci::Rectf& drawn,
                                      const ci::Rectf& clip, float driftPx,
                                      float maxRotDeg);

} // namespace slc::anim
