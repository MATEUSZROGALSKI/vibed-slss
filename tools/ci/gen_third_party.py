#!/usr/bin/env python3
"""Doc 8.4 - generate THIRD_PARTY.md + a CycloneDX SBOM from vcpkg's
installed metadata (<vcpkg_installed>/<triplet>/share/<port>/{vcpkg.spdx.json,
copyright}). Cinder is fetched outside vcpkg; pass extra entries with
--extra name=version=license=copyright_file.

Usage: gen_third_party.py <vcpkg_installed_dir>
           --out-md THIRD_PARTY.md --out-sbom sbom.cdx.json
           [--extra Cinder=0.9.3=BSD-3-Clause=path/to/COPYING ...]
"""
import argparse
import datetime
import json
import sys
import uuid
from pathlib import Path


def collect(installed: Path) -> list[dict]:
    ports = []
    # Pick the triplet dir (contains share/); skip vcpkg's own metadata dir.
    triplet = next(
        (d for d in sorted(installed.iterdir())
         if d.is_dir() and (d / "share").is_dir()),
        None)
    if triplet is None:
        sys.exit(f"no installed triplet under {installed}")
    share = triplet / "share"
    for port_dir in sorted(share.iterdir()):
        info = {"name": port_dir.name, "version": "unknown",
                "license": "unknown", "copyright": None}
        spdx = port_dir / "vcpkg.spdx.json"
        if spdx.exists():
            try:
                doc = json.loads(spdx.read_text(encoding="utf-8"))
                for pkg in doc.get("packages", []):
                    info["version"] = pkg.get("versionInfo", info["version"])
                    lic = pkg.get("licenseConcluded") or pkg.get(
                        "licenseDeclared")
                    if lic and lic != "NOASSERTION":
                        info["license"] = lic
                    break
            except (json.JSONDecodeError, OSError):
                pass
        cr = port_dir / "copyright"
        if cr.exists():
            try:
                info["copyright"] = cr.read_text(
                    encoding="utf-8", errors="replace").strip()
            except OSError:
                pass
        ports.append(info)
    return ports


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("installed", type=Path)
    ap.add_argument("--out-md", type=Path)
    ap.add_argument("--out-sbom", type=Path)
    ap.add_argument("--extra", action="append", default=[],
                    help="name=version=license=copyright_path")
    ap.add_argument("--manifest", type=Path,
                    help="vcpkg.json — when given, only deps of the listed "
                         "features (plus top-level deps) are included")
    ap.add_argument("--features", default="enrichment",
                    help="comma-separated manifest features to include")
    args = ap.parse_args()

    ports = collect(args.installed)

    if args.manifest and args.manifest.exists():
        manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
        wanted = {d["name"] if isinstance(d, dict) else d
                  for d in manifest.get("dependencies", [])}
        feats = manifest.get("features", {})
        for feat in args.features.split(","):
            deps = feats.get(feat, {}).get("dependencies", [])
            wanted.update(d["name"] if isinstance(d, dict) else d
                          for d in deps)
        ports = [p for p in ports if p["name"] in wanted]

    for spec in args.extra:
        name, _, rest = spec.partition("=")
        version, _, rest = rest.partition("=")
        license_, _, cr_path = rest.partition("=")
        copyright_ = Path(cr_path).read_text(
            encoding="utf-8", errors="replace").strip() if cr_path else None
        ports.append({"name": name, "version": version or "unknown",
                      "license": license_ or "unknown",
                      "copyright": copyright_})

    # Skip vcpkg-internal helper ports - they are build machinery, not
    # shipped dependencies.
    shipped = [p for p in ports
               if not p["name"].startswith(("vcpkg-", "pkgconfig", "doc",
                                            "man"))]

    if args.out_md:
        lines = ["# Third-party components", "",
                 "SteamLibraryScreensaver bundles or links the following "
                 "third-party software. Generated by "
                 "`tools/ci/gen_third_party.py` from vcpkg installed "
                 "metadata.", ""]
        for p in shipped:
            lines.append(f"## {p['name']} {p['version']}")
            lines.append("")
            lines.append(f"License: {p['license']}")
            lines.append("")
            if p["copyright"]:
                lines.append("```")
                lines.append(p["copyright"])
                lines.append("```")
                lines.append("")
        args.out_md.write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {args.out_md} ({len(shipped)} components)")

    if args.out_sbom:
        sbom = {
            "bomFormat": "CycloneDX",
            "specVersion": "1.5",
            "serialNumber": f"urn:uuid:{uuid.uuid4()}",
            "version": 1,
            "metadata": {
                "timestamp": datetime.datetime.now(
                    datetime.timezone.utc).isoformat(),
                "component": {
                    "type": "application",
                    "name": "steam-library-screensaver",
                },
            },
            "components": [
                {
                    "type": "library",
                    "name": p["name"],
                    "version": p["version"],
                    "licenses": [{"license": {"name": p["license"]}}],
                }
                for p in shipped
            ],
        }
        args.out_sbom.write_text(json.dumps(sbom, indent=2),
                                 encoding="utf-8")
        print(f"wrote {args.out_sbom} ({len(shipped)} components)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
